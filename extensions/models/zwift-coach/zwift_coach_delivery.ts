/**
 * Local delivery adapters for the coach: local workouts folder, sync folder
 * and portable bundle. SSH is deliberately not implemented here; the SSH
 * workflow delegates to `@swamp/ssh`.
 *
 * @module
 */

import { join } from "node:path";
import type { Plan } from "./zwift_coach_types.ts";

export type DeliveryMode = "local" | "sync" | "bundle";

export interface RenderWorkout {
  id: string;
  date: string;
  title: string;
  type: string;
  filename: string;
  xml: string;
  size: number;
  hash: string;
  errors: string[];
}

export interface DeliverOptions {
  mode: DeliveryMode;
  planId: string;
  plan?: Plan | null;
  riderId?: string;
  subfolder: string;
  workoutsDir?: string;
  syncDir?: string;
  bundleDir?: string;
  program?: string;
  prune?: boolean;
  pruneLegacy?: boolean;
  refreshIndex?: boolean;
  dryRun?: boolean;
}

export interface DeliverResult {
  mode: DeliveryMode;
  destination: string;
  written: string[];
  skipped: string[];
  pruned: string[];
  legacyPruned: string[];
  warnings: string[];
}

export const MARKER = "generated by @svendowideit/zwift-coach";

export interface SshTransportOptions {
  user?: string;
  key?: string;
  port?: number;
  hostKeyChecking?: string;
}

/** Build an @swamp/ssh transport, omitting empty user/key overrides. */
export function buildSshTransport(
  opts: SshTransportOptions = {},
): Record<string, unknown> {
  const transport: Record<string, unknown> = {
    kind: "ssh",
    port: opts.port ?? 22,
    strictHostKeyChecking: opts.hostKeyChecking ?? "accept-new",
  };
  if (opts.user) transport.user = opts.user;
  if (opts.key) transport.identityFile = opts.key;
  return transport;
}

function assertSegment(name: string, label: string): void {
  if (
    name === "" || name === "." || name === ".." || name.includes("/") ||
    name.includes("\\") || name.includes("\0")
  ) {
    throw new Error(
      `${label} is not a safe path segment: ${JSON.stringify(name)}`,
    );
  }
}

function hasMarker(content: string): boolean {
  return content.includes(MARKER);
}

async function exists(path: string): Promise<boolean> {
  try {
    await Deno.stat(path);
    return true;
  } catch {
    return false;
  }
}

async function atomicWrite(path: string, content: string): Promise<void> {
  const tmp = `${path}.tmp-${crypto.randomUUID()}`;
  await Deno.writeTextFile(tmp, content);
  try {
    await Deno.rename(tmp, path);
  } catch {
    // Windows cannot always rename over an existing file.
    await Deno.remove(path).catch(() => {});
    await Deno.rename(tmp, path);
  }
}

async function pruneMarked(
  dir: string,
  keep: Set<string>,
  dryRun: boolean,
): Promise<string[]> {
  const removed: string[] = [];
  for await (const entry of Deno.readDir(dir)) {
    if (!entry.isFile || !entry.name.endsWith(".zwo")) continue;
    if (keep.has(entry.name)) continue;
    const path = join(dir, entry.name);
    const content = await Deno.readTextFile(path).catch(() => "");
    if (!hasMarker(content)) continue;
    removed.push(entry.name);
    if (!dryRun) await Deno.remove(path);
  }
  return removed;
}

async function pruneLegacyFlat(
  parent: string,
  dryRun: boolean,
): Promise<string[]> {
  const removed: string[] = [];
  for await (const entry of Deno.readDir(parent)) {
    if (!entry.isFile || !entry.name.endsWith(".zwo")) continue;
    const path = join(parent, entry.name);
    const content = await Deno.readTextFile(path).catch(() => "");
    if (!hasMarker(content)) continue;
    removed.push(entry.name);
    if (!dryRun) await Deno.remove(path);
  }
  // Older code wrote into <parent>/default; remove only marked files there.
  const defaultDir = join(parent, "default");
  try {
    for await (const entry of Deno.readDir(defaultDir)) {
      if (!entry.isFile || !entry.name.endsWith(".zwo")) continue;
      const path = join(defaultDir, entry.name);
      const content = await Deno.readTextFile(path).catch(() => "");
      if (!hasMarker(content)) continue;
      removed.push(`default/${entry.name}`);
      if (!dryRun) await Deno.remove(path);
    }
    if (!dryRun) await Deno.remove(defaultDir).catch(() => {});
  } catch {
    // No legacy default folder.
  }
  return removed;
}

async function writeToDirectory(
  workouts: RenderWorkout[],
  dir: string,
  opts: DeliverOptions,
  legacyParent?: string,
): Promise<DeliverResult> {
  const result: DeliverResult = {
    mode: opts.mode,
    destination: dir,
    written: [],
    skipped: [],
    pruned: [],
    legacyPruned: [],
    warnings: [],
  };
  if (!opts.dryRun) await Deno.mkdir(dir, { recursive: true });
  const keep = new Set(workouts.map((w) => w.filename));
  for (const workout of workouts) {
    if (workout.errors.length > 0) {
      throw new Error(
        `refusing to deliver invalid workout ${workout.id}: ${
          workout.errors.join(", ")
        }`,
      );
    }
    assertSegment(workout.filename, "workout filename");
    const path = join(dir, workout.filename);
    if (await exists(path)) {
      const current = await Deno.readTextFile(path).catch(() => "");
      if (!hasMarker(current)) {
        throw new Error(
          `refusing to overwrite ${path}: existing file has no coach marker`,
        );
      }
      result.skipped.push(workout.filename);
    } else {
      result.written.push(workout.filename);
    }
    if (!opts.dryRun) await atomicWrite(path, workout.xml);
  }
  if (opts.prune) {
    result.pruned = await pruneMarked(dir, keep, opts.dryRun ?? false);
  }
  if (legacyParent && opts.pruneLegacy) {
    result.legacyPruned = await pruneLegacyFlat(
      legacyParent,
      opts.dryRun ?? false,
    );
  }
  return result;
}

function planMarkdown(plan: Plan | null | undefined): string {
  if (!plan) return "";
  const lines = [
    `# ${plan.summary.focus} plan`,
    "",
    `Start ${plan.startDate} · ${plan.summary.daysPerWeek} days/week · ` +
    `${plan.summary.hoursPerWeek} h/week · target CTL ${plan.summary.targetCtl}`,
    "",
  ];
  for (const week of plan.weeks) {
    lines.push(`## Week ${week.index} — ${week.theme}`, "");
    for (const session of week.sessions) {
      lines.push(
        `- ${session.date} **${session.title}** — ${session.hook} ` +
          `(${session.durationMinutes} min, ~${session.computedTss} TSS)`,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

async function writeBundle(
  workouts: RenderWorkout[],
  opts: DeliverOptions,
): Promise<DeliverResult> {
  const base = opts.bundleDir || ".swamp/zwift-coach/bundles";
  assertSegment(opts.planId, "plan id");
  const dir = join(base, `bundle-${opts.planId}`);
  const workoutsDir = join(dir, "workouts");
  const result: DeliverResult = {
    mode: "bundle",
    destination: dir,
    written: [],
    skipped: [],
    pruned: [],
    legacyPruned: [],
    warnings: [],
  };
  if (!opts.dryRun) {
    await Deno.mkdir(workoutsDir, { recursive: true });
    for (const workout of workouts) {
      assertSegment(workout.filename, "workout filename");
      await Deno.writeTextFile(
        join(workoutsDir, workout.filename),
        workout.xml,
      );
      result.written.push(workout.filename);
    }
    await Deno.writeTextFile(join(dir, "plan.md"), planMarkdown(opts.plan));
    await Deno.writeTextFile(
      join(dir, "plan.json"),
      JSON.stringify(opts.plan ?? {}, null, 2),
    );
    await Deno.writeTextFile(
      join(dir, "manifest.json"),
      JSON.stringify(
        {
          planId: opts.planId,
          generatedAt: new Date().toISOString(),
          files: workouts.map((w) => ({
            id: w.id,
            date: w.date,
            filename: w.filename,
            hash: w.hash,
            size: w.size,
          })),
        },
        null,
        2,
      ),
    );
    await Deno.writeTextFile(
      join(dir, "README.txt"),
      "Copy workouts/ into <Zwift>/Workouts/<riderId>/zwift-coach/ and restart Zwift.\n",
    );
  } else {
    result.written = workouts.map((w) => w.filename);
  }
  return result;
}

/** Deliver the rendered workouts through one local adapter. */
export async function deliverWorkouts(
  workouts: RenderWorkout[],
  opts: DeliverOptions,
): Promise<DeliverResult> {
  if (opts.mode === "bundle") return writeBundle(workouts, opts);
  if (opts.mode === "local") {
    if (!opts.workoutsDir) {
      throw new Error("local delivery needs workoutsDir");
    }
    if (!opts.riderId) throw new Error("local delivery needs riderId");
    assertSegment(opts.riderId, "rider id");
    assertSegment(opts.subfolder, "subfolder");
    if (opts.program) assertSegment(opts.program, "program");
    const parent = join(opts.workoutsDir, opts.riderId, opts.subfolder);
    const result = await writeToDirectory(
      workouts,
      opts.program ? join(parent, opts.program) : parent,
      opts,
      opts.program ? parent : undefined,
    );
    if (opts.refreshIndex) {
      await Deno.remove(
        join(opts.workoutsDir, opts.riderId, "workouts.files"),
      ).catch(() => {});
    }
    return result;
  }
  if (!opts.syncDir) throw new Error("sync delivery needs syncDir");
  assertSegment(opts.subfolder, "subfolder");
  if (opts.program) assertSegment(opts.program, "program");
  const parent = join(opts.syncDir, opts.subfolder);
  return writeToDirectory(
    workouts,
    opts.program ? join(parent, opts.program) : parent,
    opts,
    opts.program ? parent : undefined,
  );
}
